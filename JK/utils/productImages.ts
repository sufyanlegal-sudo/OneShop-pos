export interface ProductLike {
  nameUr?: string;
  nameEn?: string;
  categoryUr?: string;
  categoryEn?: string;
  preset?: string;
  image?: string;
}

/**
 * Returns the best image URL for any product:
 * 1. If product has custom `image` field, returns it.
 * 2. If not, analyzes name/category/preset and returns the crisp vector illustration.
 */
export function getProductImageUrl(p: ProductLike): string {
  if (p.image && p.image.trim().length > 0) {
    return p.image;
  }

  const text = `${p.nameUr || ''} ${p.nameEn || ''} ${p.categoryUr || ''} ${p.categoryEn || ''} ${p.preset || ''}`.toLowerCase();

  // Denim & Jeans
  if (
    text.includes('جینز') ||
    text.includes('ڈینم') ||
    text.includes('پینٹ') ||
    text.includes('jeans') ||
    text.includes('denim') ||
    text.includes('pant') ||
    text.includes('trouser')
  ) {
    return JEANS_SVG;
  }

  // T-Shirt & Polo
  if (text.includes('ٹی شرٹ') || text.includes('ٹی-شرٹ') || text.includes('t-shirt') || text.includes('tshirt') || text.includes('polo')) {
    return TSHIRT_SVG;
  }

  // Formal Shirt
  if (text.includes('شرٹ') || text.includes('shirt')) {
    return SHIRT_FORMAL_SVG;
  }

  // Traditional Kurta / Shalwar / Suit
  if (
    text.includes('کرتا') ||
    text.includes('شلوار') ||
    text.includes('سوٹ') ||
    text.includes('فراک') ||
    text.includes('kurta') ||
    text.includes('shalwar') ||
    text.includes('suit') ||
    text.includes('frock') ||
    text.includes('lawn')
  ) {
    return KURTA_SVG;
  }

  // Edible Oil & Ghee
  if (text.includes('تیل') || text.includes('گھی') || text.includes('oil') || text.includes('ghee')) {
    return OIL_BOTTLE_SVG;
  }

  // Shampoo, Lotion & Liquids
  if (
    text.includes('شیمپو') ||
    text.includes('لوشن') ||
    text.includes('shampoo') ||
    text.includes('lotion') ||
    text.includes('vaseline') ||
    text.includes('فینائل') ||
    text.includes('ڈش واش')
  ) {
    return SHAMPOO_BOTTLE_SVG;
  }

  // Soaps & Detergents
  if (
    text.includes('صابن') ||
    text.includes('سرف') ||
    text.includes('soap') ||
    text.includes('detergent') ||
    text.includes('surf') ||
    text.includes('safeguard') ||
    text.includes('dettol')
  ) {
    return SOAP_BAR_SVG;
  }

  // Cold Drinks & Juices
  if (
    text.includes('ڈرنک') ||
    text.includes('جوس') ||
    text.includes('شربت') ||
    text.includes('کوک') ||
    text.includes('پیپسی') ||
    text.includes('drink') ||
    text.includes('juice') ||
    text.includes('cola') ||
    text.includes('water')
  ) {
    return DRINK_CAN_SVG;
  }

  // Bakery & Sweets
  if (
    text.includes('کیک') ||
    text.includes('بسکٹ') ||
    text.includes('مٹھائی') ||
    text.includes('cake') ||
    text.includes('biscuit') ||
    text.includes('sweet') ||
    text.includes('bread') ||
    text.includes('روٹی')
  ) {
    return BAKERY_CAKE_SVG;
  }

  // Grocery, Flour, Rice, Sugar
  if (
    text.includes('چاول') ||
    text.includes('چینی') ||
    text.includes('دال') ||
    text.includes('آٹا') ||
    text.includes('rice') ||
    text.includes('sugar') ||
    text.includes('flour') ||
    text.includes('daal') ||
    text.includes('pulses') ||
    p.preset === 'grocery'
  ) {
    return GROCERY_PACK_SVG;
  }

  // Default clean retail product package
  return GENERAL_PACKAGE_SVG;
}

